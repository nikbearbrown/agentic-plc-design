"""Generate a DraftSight/AutoCAD AutoLISP job file from a variant.

The output is DRY-RUN by default: command APD-DRYRUN reports what would change,
command APD-APPLY changes it. Run on a COPY of the drawing.
"""
from __future__ import annotations

import argparse
from pathlib import Path

import design


def esc(s: str) -> str:
    return str(s).replace("\\", "\\\\").replace('"', '\\"')


DEFAULT_TAGS = {"job_name": "JOBNAME", "job_number": "JOBNUMBER", "revision": "REV",
                "voltage": "VOLTAGE", "pump_hp": "PUMPHP"}


def generate(variant: dict, block="TITLEBLOCK", swaps=(), tags=None, lib="apd-lib.lsp") -> str:
    """tags maps field -> YOUR attribute tag name, e.g. {"job_name": "PROJECT_TITLE"}."""
    tagmap = {**DEFAULT_TAGS, **(tags or {})}
    j, p, pw = variant["job"], variant["pumps"], variant["power"]
    values = {"job_name": j["name"], "job_number": j["number"], "revision": j["revision"],
              "voltage": f"{pw['voltage']}V {pw['phase']}PH {pw['hz']}HZ", "pump_hp": f"{p['hp']} HP"}
    attrs = {tagmap[k]: v for k, v in values.items()}
    lines = [
        ";;; Generated by tools/lisp_gen.py from the variant file. Do not hand-edit; regenerate.",
        ";;; Requires apd-lib.lsp. DRY RUN unless you type APD-APPLY. Work on a COPY.",
        f'(load "{esc(lib)}")',
        "",
        "(defun apd-job-run ( / ss i)",
        f'  (setq ss (ssget "_X" \'((0 . "INSERT") (2 . "{esc(block)}"))))',
        "  (if ss",
        "    (progn",
        "      (setq i 0)",
        "      (while (< i (sslength ss))",
    ]
    for tag, val in attrs.items():
        lines.append(f'        (apd-set-attrib (ssname ss i) "{tag}" "{esc(val)}")')
    lines += [
        "        (setq i (1+ i))",
        "      )",
        "    )",
        f'    (apd-log "No block named {esc(block)} found")',
        "  )",
    ]
    for old, new in swaps:
        lines.append(f'  (apd-replace-text "{esc(old)}" "{esc(new)}")')
    lines += [
        "  (princ)",
        ")",
        "",
        "(defun c:APD-DRYRUN () (setq *APD-APPLY* nil) (apd-job-run))",
        "(defun c:APD-APPLY ()",
        '  (apd-log "APPLYING. Undo with U if this is not a copy.")',
        "  (setq *APD-APPLY* T)",
        "  (apd-job-run)",
        "  (setq *APD-APPLY* nil)",
        "  (princ)",
        ")",
        '(apd-log "Loaded. Commands: APD-DRYRUN, APD-APPLY")',
        "(princ)",
        "",
    ]
    return "\n".join(lines)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("variant")
    ap.add_argument("--block", default="TITLEBLOCK")
    ap.add_argument("--swap", action="append", default=[], help='"old=new" text replacement, repeatable')
    ap.add_argument("--tag", action="append", default=[],
                    help="field=ATTRIBUTE_TAG, repeatable; fields: " + ", ".join(DEFAULT_TAGS))
    ap.add_argument("--lib", default="apd-lib.lsp", help="path to apd-lib.lsp, forward slashes, e.g. C:/lisp/apd-lib.lsp")
    a = ap.parse_args(argv)
    swaps = [tuple(s.split("=", 1)) for s in a.swap]
    tags = dict(t.split("=", 1) for t in a.tag)
    print(generate(design.load_toml(a.variant), a.block, swaps, tags, a.lib))


if __name__ == "__main__":
    main()
